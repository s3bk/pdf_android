#!/usr/bin/env python3
"""Extract the word "PDF" from the app's own Inter.ttf as plain path data.

The icon must not depend on a font at runtime (an Android VectorDrawable has no
text), so the three glyphs are converted to outlines here, once, and baked into
letters.py as SVG path data in icon (512x512) coordinates.

    assets/Inter.ttf, variable Inter, upem 2048, cap height 1490
    instance: wght 700, opsz 32

Run:  python3 extract_letters.py     (needs fonttools)
"""
import os
import re

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.misc.transform import Transform

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(HERE, "..", "assets", "Inter.ttf")

# --- icon geometry the word has to live in (keep in sync with draw_icon.py) --
CX = 256.0
CY = 256.0
CAP_H = 62.0          # cap height in canvas units
TRACK = -12.0         # letterspacing, font units
WORD = "PDF"


def main():
    f = TTFont(FONT)
    upem = f["head"].unitsPerEm
    cap = f["OS/2"].sCapHeight
    f = instancer.instantiateVariableFont(f, {"wght": 700, "opsz": 32})
    glyphs = f.getGlyphSet()
    cmap = f.getBestCmap()
    hmtx = f["hmtx"]

    s = CAP_H / cap
    # first pass: advances, to centre the ink
    advances = [hmtx[cmap[ord(c)]][0] for c in WORD]
    total = sum(advances) + TRACK * (len(WORD) - 1)
    inks = [f["glyf"][cmap[ord(c)]] for c in WORD]
    ink_l = inks[0].xMin
    ink_r = total - advances[-1] + inks[-1].xMax
    x0 = CX - (ink_r - ink_l) * s / 2.0 - ink_l * s
    y_base = CY + CAP_H / 2.0

    parts = []
    pen_x = 0.0
    for ch, adv in zip(WORD, advances):
        name = cmap[ord(ch)]
        spen = SVGPathPen(glyphs)
        t = Transform(s, 0, 0, -s, x0 + pen_x * s, y_base)
        glyphs[name].draw(TransformPen(spen, t))
        parts.append(spen.getCommands())
        pen_x += adv + TRACK
        print("%s  advance %4d  bbox %s" % (ch, adv, (inks[WORD.index(ch)].xMin,
                                                      inks[WORD.index(ch)].xMax)))

    path = " ".join(parts)
    path = re.sub(r"(?<![0-9.])(-?[0-9]+\.[0-9]+)", lambda m: "%g" % round(float(m.group(1)), 2), path)
    out = os.path.join(HERE, "letters.py")
    with open(out, "w") as fh:
        fh.write('"""Generated by extract_letters.py from assets/Inter.ttf '
                 '(wght 700, opsz 32).  Do not edit."""\n\n')
        fh.write("CAP_H = %.1f\n" % CAP_H)
        fh.write("INK_L = %.2f\n" % (x0 + ink_l * s))
        fh.write("INK_R = %.2f\n" % (x0 + ink_r * s))
        fh.write("INK_T = %.2f\n" % (y_base - cap * s))
        fh.write("INK_B = %.2f\n" % (y_base - (inks[0].yMin) * s))
        fh.write("PDF_PATH = (\n")
        for chunk in range(0, len(path), 96):
            fh.write("    %r\n" % path[chunk:chunk + 96])
        fh.write(")\n")
    print("wrote", os.path.relpath(out, HERE),
          "%.0f x %.0f canvas units" % ((ink_r - ink_l) * s, cap * s))


if __name__ == "__main__":
    main()
